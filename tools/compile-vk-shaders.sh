#!/usr/bin/env bash
# Compiles the Vulkan panel's HDR shaders (src/panel/shaders/panel_vk_hdr.hlsl) to SPIR-V and writes them as arrays
# into src/panel/panel_vk_shaders.h, which is checked in: building Gyro4All needs no shader compiler. Run it after
# editing the HLSL. Needs DXC with SPIR-V output (the Windows SDK's dxc has none): the GitHub release in
# third_party/dxc-<version>/ (https://github.com/microsoft/DirectXShaderCompiler/releases), or DXC=<path to dxc.exe>.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
dxc="${DXC:-$(ls -d "$root"/third_party/dxc-*/bin/x64/dxc.exe 2>/dev/null | tail -1)}"
[ -x "$dxc" ] || { echo "no dxc.exe with SPIR-V output: set DXC or unpack the DXC release into third_party/dxc-<version>" >&2; exit 1; }
src="$root/src/panel/shaders/panel_vk_hdr.hlsl"
out="$root/src/panel/panel_vk_shaders.h"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

compile() {  # entry, profile
    "$dxc" -spirv -fspv-target-env=vulkan1.0 -O3 -T "$2" -E "$1" "$(cygpath -w "$src" 2>/dev/null || echo "$src")" \
        -Fo "$(cygpath -w "$tmp/$1.spv" 2>/dev/null || echo "$tmp/$1.spv")"
}
compile vs vs_6_0
compile ps_scrgb ps_6_0
compile ps_hdr10 ps_6_0
compile ps_hdr10_pq ps_6_0

python -I - "$tmp" "$out" "$("$dxc" --version 2>&1 | head -1)" <<'EOF'
import struct, sys
tmp, out, version = sys.argv[1], sys.argv[2], sys.argv[3]
lines = ["// Generated by tools/compile-vk-shaders.sh from shaders/panel_vk_hdr.hlsl (" + version.strip() + "). Do not edit.",
         "#pragma once", "#include <cstdint>", ""]
for name in ("vs", "ps_scrgb", "ps_hdr10", "ps_hdr10_pq"):
    data = open(f"{tmp}/{name}.spv", "rb").read()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines.append(f"inline constexpr uint32_t kSpirv_{name}[] = {{")
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
    lines.append("};")
open(out, "w", newline="\n").write("\n".join(lines) + "\n")
EOF
echo "wrote $out"
